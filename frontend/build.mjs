// Bundles src/console.js (+ maplibre-gl) into ../static/console.js and merges the CSS into ../static/console.css
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

mkdirSync("../static", { recursive: true });
await build({
  entryPoints: ["src/console.js"],
  bundle: true,
  format: "esm",
  minify: true,
  target: "es2020",
  legalComments: "none",
  banner: { js: "// Operations console: MapLibre GL + dashboard UI (generated by frontend/build.mjs)" },
  outfile: "../static/console.js",
});
const css = readFileSync("node_modules/maplibre-gl/dist/maplibre-gl.css", "utf8") + "\n" + readFileSync("src/console.css", "utf8");
writeFileSync("../static/console.css", css);
console.log("built");
